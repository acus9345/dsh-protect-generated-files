import { test } from 'node:test'
import assert from 'node:assert/strict'
import { pluginEntry, runDsh } from './helpers/dsh.ts'

const plugin = { id: 'protect-generated-files', entry: pluginEntry }
const gen = '// Code generated by sqlc. DO NOT EDIT.\npackage db\n\nconst q = "select 1"\n'

test('editing a generated file is blocked with a regeneration hint', async () => {
  const run = await runDsh({
    plugins: [plugin],
    files: { 'db/query.sql.go': gen, 'pnpm-lock.yaml': 'lockfileVersion: 9.0\n' },
    readAfter: ['db/query.sql.go', 'pnpm-lock.yaml'],
    script: [
      { tool: 'read', input: { file_path: 'db/query.sql.go' } },
      { tool: 'edit', input: { file_path: 'db/query.sql.go', old_string: 'select 1', new_string: 'select 2' } },
      { tool: 'bash', input: { description: 'Patch lockfile', command: "sed -i 's/9.0/6.0/' pnpm-lock.yaml" } },
    ],
  })
  assert.equal(run.exitCode, 0, run.stderr)
  assert.match(run.toolResults[1]!.result, /protect-generated-files blocked this edit to db\/query\.sql\.go/)
  assert.match(run.toolResults[1]!.result, /sqlc generate/)
  assert.match(run.toolResults[2]!.result, /pnpm add/)
  assert.equal(run.filesAfter['db/query.sql.go'], gen)
  assert.equal(run.filesAfter['pnpm-lock.yaml'], 'lockfileVersion: 9.0\n')
})

test('normal files are untouched by the guard', async () => {
  const run = await runDsh({
    plugins: [plugin],
    files: { 'src/a.ts': 'export const a = 1\n' },
    readAfter: ['src/a.ts'],
    script: [
      { tool: 'read', input: { file_path: 'src/a.ts' } },
      { tool: 'edit', input: { file_path: 'src/a.ts', old_string: '= 1', new_string: '= 2' } },
    ],
  })
  assert.equal(run.toolResults[1]!.status, 'completed')
  assert.equal(run.filesAfter['src/a.ts'], 'export const a = 2\n')
})

test('works when installed with `dsh plugin add`', async () => {
  const run = await runDsh({
    installed: true,
    files: { 'db/query.sql.go': gen },
    script: [
      { tool: 'read', input: { file_path: 'db/query.sql.go' } },
      { tool: 'edit', input: { file_path: 'db/query.sql.go', old_string: 'select 1', new_string: 'select 2' } },
    ],
  })
  assert.equal(run.exitCode, 0, run.stderr)
  assert.match(run.toolResults[1]!.result, /protect-generated-files blocked this edit/)
})

test('guards the pwsh tool too (the shell DSH uses on Windows)', async () => {
  const run = await runDsh({
    plugins: [plugin],
    homePatch: '- id: tool-pwsh\n  disabled: false\n- id: tool-bash\n  disabled: true\n',
    files: { 'pnpm-lock.yaml': 'lockfileVersion: 9.0\n' },
    readAfter: ['pnpm-lock.yaml'],
    script: [{ tool: 'pwsh', input: { description: 'Patch lockfile', command: "(Get-Content pnpm-lock.yaml) -replace '9.0','6.0' | Set-Content pnpm-lock.yaml" } }],
  })
  assert.equal(run.exitCode, 0, run.stderr)
  assert.match(run.toolResults[0]!.result, /protect-generated-files blocked/)
  assert.equal(run.filesAfter['pnpm-lock.yaml'], 'lockfileVersion: 9.0\n')
})
