import { test } from 'node:test'
import assert from 'node:assert/strict'
import { generatedInfo, hintFor } from '../src/detect.ts'
import { shellEditTargets } from '../src/index.ts'

test('lockfiles are generated, with the right command', () => {
  const info = generatedInfo('pnpm-lock.yaml', undefined)
  assert.equal(info?.via, 'path')
  assert.match(info!.hint, /pnpm add/)
  assert.match(generatedInfo('apps/web/package-lock.json', undefined)!.hint, /npm install/)
  assert.match(generatedInfo('Cargo.lock', undefined)!.hint, /cargo/)
  assert.match(generatedInfo('go.sum', undefined)!.hint, /go mod tidy/)
})

test('known output paths are generated', () => {
  assert.equal(generatedInfo('api/v1/user.pb.go', undefined)?.evidence, '*.pb.go')
  assert.equal(generatedInfo('dist/index.js', undefined)?.evidence, '**/dist/**')
  assert.equal(generatedInfo('node_modules/react/index.js', undefined)?.evidence, '**/node_modules/**')
  assert.equal(generatedInfo('src/__generated__/graphql.ts', undefined)?.evidence, '**/__generated__/**')
})

test('header markers are detected with a tool-specific hint', () => {
  const go = '// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: user.proto\npackage api\n'
  const info = generatedInfo('api/user.go', go)
  assert.equal(info?.via, 'marker')
  assert.match(info!.hint, /\.proto/)
  assert.match(generatedInfo('src/db.ts', '/**\n * @generated by sqlc. Do not edit.\n */\n')!.hint, /sqlc generate/)
  assert.match(generatedInfo('src/client.ts', '// This file was auto-generated by openapi-typescript.\n')!.hint, /OpenAPI/)
  assert.match(generatedInfo('x.ts', '// Generated by tool-x from schema.json\n')!.hint, /schema\.json/)
})

test('ordinary files are not generated', () => {
  assert.equal(generatedInfo('src/index.ts', 'export const a = 1\n'), undefined)
  assert.equal(generatedInfo('src/gen.ts', 'export function generatedBy() {}\n'), undefined)
  assert.equal(generatedInfo('README.md', '# Project\n\nThe docs are generated by people.\n'), undefined)
  assert.equal(generatedInfo('src/later.ts', '\n'.repeat(30) + '// DO NOT EDIT\n'), undefined)
})

test('ignore and extraGlobs', () => {
  assert.equal(generatedInfo('dist/index.js', undefined, { ignore: ['dist/**'] }), undefined)
  assert.equal(generatedInfo('src/api/client/user.ts', undefined, { extraGlobs: { 'src/api/client/**': 'run npm run gen' } })?.hint, 'run npm run gen')
  assert.equal(generatedInfo('dist/index.js', undefined, { defaultGlobs: false }), undefined)
  assert.ok(generatedInfo('yarn.lock', undefined, { defaultGlobs: false }))
})

test('hintFor falls back to a generic hint', () => {
  assert.match(hintFor('// DO NOT EDIT'), /regenerate/)
})

test('shellEditTargets', () => {
  assert.deepEqual(shellEditTargets("sed -i 's/a/b/' yarn.lock"), ['yarn.lock'])
  assert.deepEqual(shellEditTargets("perl -pi -e 's/a/b/' go.sum"), ['go.sum'])
  assert.deepEqual(shellEditTargets('echo x > dist/a.js'), ['dist/a.js'])
  assert.deepEqual(shellEditTargets('npm test 2>&1 | tee out.log'), ['out.log'])
  assert.deepEqual(shellEditTargets('ls > /dev/null'), [])
})

test('"generated by" a person or a chat assistant is not a generated file', () => {
  const o = { extraGlobs: {}, ignore: [], defaultGlobs: true, headerLines: 15 }
  assert.equal(generatedInfo('src/a.ts', '// Generated by hand\nexport const x = 1\n', o), undefined)
  assert.equal(generatedInfo('src/a.ts', '# generated by ChatGPT, then reviewed\n', o), undefined)
  assert.ok(generatedInfo('src/a.ts', '// Generated by orval v6.31\n', o))
})

test('build-output folder names deep inside sources are not generated', () => {
  const roots = new Set(['', 'packages/ui'])
  const o = { extraGlobs: {}, ignore: [], defaultGlobs: true, headerLines: 15, isProjectRoot: (d: string) => roots.has(d) }
  assert.equal(generatedInfo('src/main/java/com/acme/target/Target.java', 'package x;', o), undefined)
  assert.equal(generatedInfo('src/components/dist/Distance.tsx', 'export {}', o), undefined)
  assert.equal(generatedInfo('app/vendor/custom.css', 'a{}', o), undefined)
  assert.ok(generatedInfo('packages/ui/dist/index.js', 'x', o))
  assert.ok(generatedInfo('target/debug/build.rs', 'x', o))
})

test('headers that allow edits, or qualify DO NOT EDIT, are not generated markers', () => {
  const o = { extraGlobs: {}, ignore: [], defaultGlobs: true, headerLines: 15 }
  assert.equal(generatedInfo('src/a.ts', '// DO NOT EDIT without updating docs/api.md\n', o), undefined)
  assert.equal(generatedInfo('src/a.ts', '/**\n * Generated once with plop, edit freely.\n */\n', o), undefined)
  assert.ok(generatedInfo('README.md', '<!-- DO NOT EDIT: generated by readme-gen -->\n', o))
})

test('PowerShell in-place writes are seen', () => {
  assert.deepEqual(shellEditTargets("(Get-Content pnpm-lock.yaml) -replace '9.0','6.0' | Set-Content pnpm-lock.yaml"), ['pnpm-lock.yaml'])
  assert.deepEqual(shellEditTargets('"x" | Out-File -FilePath .\\src\\gen\\client.ts'), ['./src/gen/client.ts'])
  assert.deepEqual(shellEditTargets('Add-Content -Path go.sum -Value x'), ['go.sum'])
  assert.deepEqual(shellEditTargets('npm test > $null'), [])
})
